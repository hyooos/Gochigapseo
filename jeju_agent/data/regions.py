CITIES = ("제주시", "서귀포시")
JEJU_BBOX = (33.0, 34.1, 126.0, 127.1)   # 위도 최소·최대, 경도 최소·최대 (추자도 포함)


def in_jeju(lat, lng) -> bool:
    try:
        lat, lng = float(lat), float(lng)
    except (TypeError, ValueError):
        return False
    return JEJU_BBOX[0] <= lat <= JEJU_BBOX[1] and JEJU_BBOX[2] <= lng <= JEJU_BBOX[3]


def infer_emd(lat: float, lng: float) -> tuple[str, str]:
    """좌표에서 제일 가까운 읍면동 중심 (대략). 반환: (시, 읍면동)"""
    names = list(EMD)
    la = np.array([EMD[n][1] for n in names])
    lo = np.array([EMD[n][2] for n in names])
    d = (la - lat) ** 2 + ((lo - lng) * np.cos(np.radians(33.4))) ** 2
    best = names[int(np.argmin(d))]
    return EMD[best][0], best


_ADDR_EMD = re.compile(r"([가-힣]{1,4}\d?(?:읍|면|동))(?=\s|$|,|\d)")


def parse_address(addr: str | None) -> tuple[str | None, str | None]:
    """주소 → (시, 읍면동). 행정동 사전에 있는 이름만 (법정동·리는 None)"""
    if not addr or not isinstance(addr, str):
        return None, None
    city = next((c for c in CITIES if c in addr), None)
    emd = next((m for m in _ADDR_EMD.findall(addr) if m in EMD), None)
    if emd and city is None:
        city = EMD[emd][0]
    return city, emd


# 줄임말 허용하는 동 (나머지는 끝까지 써야 함: '중앙'·'오라'·'외도'는 일반 낱말이랑 겹침)
_DONG_SHORT = {"중문": "중문동", "노형": "노형동", "이호": "이호동", "삼양": "삼양동", "효돈": "효돈동"}


def region_aliases(extra: list[str] | None = None) -> dict[str, str]:
    """질문 속 표현 → 표준 지역명 ('서귀포' → '서귀포시', '중문' → '중문동')"""
    out = {"제주시": "제주시", "서귀포시": "서귀포시", "서귀포": "서귀포시", **_DONG_SHORT}
    for emd in list(EMD) + list(extra or []):
        out[emd] = emd
        if emd.endswith(("읍", "면")):     # 읍·면만 줄임말 (애월·성산·표선…)
            out.setdefault(emd[:-1], emd)
    return out


def region_center(region: str | None) -> tuple[float, float] | None:
    if region in EMD:
        return EMD[region][1], EMD[region][2]
    if region == "제주시":
        return 33.4996, 126.5312
    if region == "서귀포시":
        return 33.2541, 126.5600
    return None
